import { readFile, writeFile } from 'node:fs/promises';

// Arco also declares --color-* on body. Put the company's complete token map
// on the client scope so inherited Arco defaults cannot override it.
const source = new URL('../docs/company-design-system/sources/品信颜色映射表 v1.2.css', import.meta.url);
const destination = new URL('../src/company-color-tokens.css', import.meta.url);
const css = await readFile(source, 'utf8');
if (!/^:root\s*\{/m.test(css)) throw new Error('Company color source must contain a :root block.');
const scoped = css.replace(/^:root\s*\{/m, 'body[data-portal="client"], .duozuhu-client {');
await writeFile(destination, `/* Generated by scripts/sync-company-colors.mjs; edit the company source, then regenerate. */\n${scoped}`, 'utf8');
